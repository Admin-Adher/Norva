// Generate the database-rendered security/partner/trial shell from the same
// component used by Edge. User values stay SQL parameters, never executable SQL.
const fs = require('node:fs');
const path = require('node:path');
const { importTypescriptModule } = require('../tests/helpers/import-typescript-module');
(async () => {
  const { renderEmailFrame } = await importTypescriptModule(path.join(__dirname, '../supabase/functions/_shared/email-frame.ts'));
  const expressions = {
    NV_HEADING_TOKEN: 'public.norva_html_escape(p_heading)',
    NV_INTRO_TOKEN: "coalesce(p_intro, '')",
    NV_FOOTER_TOKEN: 'public.norva_html_escape(p_footer)',
    NV_CTA_LABEL_TOKEN: 'public.norva_html_escape(p_cta_label)',
    NV_CTA_URL_TOKEN: 'public.norva_html_escape(p_cta_url)',
    NV_ARTWORK_TOKEN: "case when p_heading ilike '%trial%' or p_heading ilike '%subscription%' or p_heading ilike '%payment%' then 'billing' when p_heading ilike '%partner%' or p_heading ilike '%support%' then 'support' else 'security' end",
  };
  const literal = value => "'" + value.replace(/'/g, "''") + "'";
  function expression(withCta) {
    const html = renderEmailFrame({ title: 'NV_HEADING_TOKEN', heading: 'NV_HEADING_TOKEN', preheader: 'NV_HEADING_TOKEN', bodyHtml: 'NV_INTRO_TOKEN', noteHtml: 'NV_FOOTER_TOKEN',
      ...(withCta ? { cta: { label: 'NV_CTA_LABEL_TOKEN', url: 'NV_CTA_URL_TOKEN' } } : {}),
    }).replace('/img/email/security-v1.jpg', '/img/email/NV_ARTWORK_TOKEN-v1.jpg');
    return html.split(/(NV_[A-Z_]+_TOKEN)/).map(x => expressions[x] || literal(x)).join(' ||\n');
  }
  const sql = `-- Generated by scripts/build-branded-email-migration.js. Presentation only.
set lock_timeout='3s';
set statement_timeout='30s';
create or replace function public.norva_branded_email_html(
 p_heading text,p_intro text,p_cta_label text default null,p_cta_url text default null,
 p_footer text default 'If you didn''t request this, please review your account security.'
) returns text language sql immutable set search_path='pg_catalog','public' as $email$
 select case when nullif(btrim(p_cta_label),'') is not null and nullif(btrim(p_cta_url),'') is not null
 then ${expression(true)}
 else ${expression(false)} end;
$email$;
`;
  const target = path.resolve(process.argv[2]);
  fs.writeFileSync(target, sql);
  console.log(JSON.stringify({ migration: target, bytes: Buffer.byteLength(sql) }));
})().catch(error => { console.error(error.message); process.exitCode = 1; });
