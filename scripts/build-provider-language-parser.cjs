'use strict';
// Mechanical mirrors: the browser remains the source of the audited hint grammar.
// SQL grammar parity is exercised separately against the same provider fixtures.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.join(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'public/js/utils/mediaUtils.js'), 'utf8').replace(/\r\n/g, '\n');
const constants = ['SUB_MARKERS', 'DUB_MARKERS', 'BAR_SEPARATORS', 'RTL_SUB_RE'].map(name =>
  source.match(new RegExp(`    const ${name} = [^\\n]+`))[0].trim()).join('\n');
const table = source.slice(source.indexOf('    const VERSION_PROVIDER_LANGUAGE_TAGS = {'), source.indexOf('\n\n    function versionProviderLanguageHint'));
const parser = source.slice(source.indexOf('    function versionProviderLanguageHint'), source.indexOf("        if (tag === 'nordic')"))
  .replace('function versionProviderLanguageHint', 'export function providerCatalogLanguage') + '        return tag;\n    }\n';
const moduleText = '// Generated by scripts/build-provider-language-parser.cjs. No observed-track semantics.\n'
  + constants + '\nconst stripDiacritics = str => String(str).normalize("NFD").replace(/[\\u0300-\\u036f]/g, "");\n'
  + table + '\n' + parser + '\nexport const PROVIDER_CATALOG_LANGUAGES = Object.freeze([...new Set(Object.values(VERSION_PROVIDER_LANGUAGE_TAGS).filter(Boolean))]);\n';
const sqlFile = 'supabase/migrations/20260910152938_catalog_provider_language_facets.sql';
const aliases = vm.runInNewContext(table + '\nVERSION_PROVIDER_LANGUAGE_TAGS');
const sql = fs.readFileSync(path.join(root, sqlFile), 'utf8');
const aliasesSql = '-- BEGIN GENERATED ALIASES\n  select ' + "'" + JSON.stringify(aliases).replaceAll("'", "''") + "'::jsonb ->> p_token;\n-- END GENERATED ALIASES";
const generatedSql = sql.replace(/-- BEGIN GENERATED ALIASES[\s\S]*?-- END GENERATED ALIASES/, aliasesSql);
for (const [file, text] of [['supabase/functions/_shared/provider-catalog-language.mjs', moduleText], [sqlFile, generatedSql]]) {
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(path.join(root, file)) || fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n') !== text.replace(/\r\n/g, '\n')) throw Error('Generated parser drift: ' + file);
  } else fs.writeFileSync(path.join(root, file), text);
}
